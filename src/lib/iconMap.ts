export function getToolIcon(icon: any) {
  if (typeof icon === "function" || (typeof icon === "object" && icon !== null)) {
    return icon;
  }
  if (typeof icon === "string" && ICON_MAP[icon]) {
    return ICON_MAP[icon];
  }
  return HelpCircle;
}
